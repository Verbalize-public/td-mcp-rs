//! Loaded bridge provenance, capability negotiation, and liveness observations.
//!
//! Connection generation is daemon-owned and is deliberately separate from
//! the bridge's per-load UUID.  A ready event is eligible only for the exact
//! connected generation that observed it.

use chrono::{DateTime, Utc};
use serde::{Deserialize, Serialize};
use thiserror::Error;

/// Capability state of the currently connected bridge generation.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub enum BridgeCapabilityState {
    /// No valid ready event was observed (legacy bridges remain usable).
    Unknown,
    /// A valid ready event was observed for this connection generation.
    Ready,
}

/// Protocol identity reported by the loaded bridge.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BridgeProtocolIdentity {
    /// Protocol family name.
    pub name: String,
    /// Exact protocol version.
    pub version: String,
}

/// Python/runtime identity reported by the loaded bridge.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BridgeRuntimeIdentity {
    /// Python implementation (for example `CPython`).
    pub implementation: String,
    /// Python runtime version.
    pub python_version: String,
    /// Runtime platform name.
    pub platform: String,
}

/// Fingerprint of selected code objects that are actually loaded.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct LoadedCodeIdentity {
    /// Identity representation kind.
    pub kind: String,
    /// Hash algorithm and framing version.
    pub algorithm: String,
    /// Hex digest.
    pub digest: String,
    /// Advertised routes/transport functions covered by the fingerprint.
    #[serde(default)]
    pub coverage: Vec<String>,
    /// Expected bindings that were unavailable while fingerprinting.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub missing: Vec<String>,
    /// Explicit limits of this identity.
    #[serde(default)]
    pub limitations: Vec<String>,
}

/// Source bytes observed on disk when readiness was built after final reload.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BridgeSourceSnapshot {
    /// Identity representation kind.
    pub kind: String,
    /// Observation provenance; this is not a claim about later disk state.
    pub provenance: String,
    /// Hash algorithm and framing version.
    pub algorithm: String,
    /// Hex digest.
    pub digest: String,
    /// Source files included in the snapshot.
    #[serde(default)]
    pub files: Vec<String>,
    /// Loaded module source paths that could not be read.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub unavailable: Vec<String>,
    /// Explicit limits of this source snapshot.
    #[serde(default)]
    pub limitations: Vec<String>,
}

/// Daemon-selected bridge package files observed on disk at readiness.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BridgeBundleSnapshot {
    /// Identity representation kind.
    pub kind: String,
    /// Observation provenance; this is not loaded-code identity or later disk state.
    pub provenance: String,
    /// Hash algorithm and framing version.
    pub algorithm: String,
    /// Hex digest.
    pub digest: String,
    /// Bundle files included in the snapshot.
    #[serde(default)]
    pub files: Vec<String>,
    /// Expected bundle paths that could not be read.
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub unavailable: Vec<String>,
    /// Explicit limits of this bundle snapshot.
    #[serde(default)]
    pub limitations: Vec<String>,
}

/// Optional post-reload event emitted by a capability-aware bridge.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BridgeReadyEvent {
    /// UUID generated by this final Python package load.
    pub load_generation: String,
    /// Loaded protocol identity.
    pub protocol: BridgeProtocolIdentity,
    /// Loaded Python/runtime identity.
    pub runtime: BridgeRuntimeIdentity,
    /// Explicit implemented route list; never inferred from a version/catalog.
    #[serde(default)]
    pub supported_features: Vec<String>,
    /// Fingerprint of selected loaded code objects.
    pub loaded_code: LoadedCodeIdentity,
    /// On-disk source snapshot for loaded modules, distinct from loaded code.
    pub source_snapshot: BridgeSourceSnapshot,
    /// Daemon-selected package files observed on disk at readiness.
    pub bundle_snapshot: BridgeBundleSnapshot,
    /// Cached pump age at readiness, when a main-thread pump already ran.
    #[serde(default)]
    pub main_thread_pump_age_ms: Option<u64>,
}

/// Metadata piggybacked on the daemon's existing internal heartbeat ping.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "camelCase")]
pub struct BridgeHeartbeatObservation {
    /// Load generation producing this pong.
    pub load_generation: String,
    /// Age of the cached main-thread pump observation.  The worker must not
    /// update that cache merely because IPC is healthy.
    #[serde(default)]
    pub main_thread_pump_age_ms: Option<u64>,
}

/// Age calculated from a fact last observed at a named boundary.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BridgeObservedAge {
    /// Wall-clock time at which the daemon observed the fact.
    pub observed_at: DateTime<Utc>,
    /// Age at response construction, derived from the last observation.
    pub age_ms: u64,
    /// Boundary that produced the fact.
    pub provenance: &'static str,
}

/// Public optional `fleet(include:["identity"])` bridge identity section.
#[derive(Debug, Clone, PartialEq, Eq, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct BridgeIdentitySnapshot {
    /// Daemon-owned connection generation.
    pub connection_generation: u64,
    /// Whether a valid ready event was observed for this generation.
    pub capability_state: BridgeCapabilityState,
    /// Bridge-generated load UUID, present only after readiness.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub load_generation: Option<String>,
    /// Loaded protocol identity, present only after readiness.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub protocol: Option<BridgeProtocolIdentity>,
    /// Loaded runtime identity, present only after readiness.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub runtime: Option<BridgeRuntimeIdentity>,
    /// Explicit implemented features. Empty means unknown, not unsupported.
    pub supported_features: Vec<String>,
    /// Fingerprint of actually loaded selected Python code objects.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub loaded_code: Option<LoadedCodeIdentity>,
    /// Source bytes for loaded modules observed at ready-after-reload time.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub source_snapshot: Option<BridgeSourceSnapshot>,
    /// Daemon-selected package files observed on disk at readiness.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub bundle_snapshot: Option<BridgeBundleSnapshot>,
    /// Last framed IPC traffic observed by the daemon.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub ipc_liveness: Option<BridgeObservedAge>,
    /// Last cached TD main-thread pump observation reported by the bridge.
    #[serde(skip_serializing_if = "Option::is_none")]
    pub main_thread_pump: Option<BridgeObservedAge>,
}

/// Per-entry state backing bridge identity snapshots.
#[derive(Debug, Clone, Default)]
pub struct BridgeIdentityState {
    /// Daemon-owned connection generation (`0` means not handshaken).
    pub connection_generation: u64,
    /// Ready metadata for this exact connection generation.
    pub ready: Option<BridgeReadyEvent>,
    /// Last framed IPC traffic observation.
    pub ipc_observed_at: Option<DateTime<Utc>>,
    /// Bridge-reported age and daemon observation time for the cached pump.
    pub main_thread_pump: Option<(DateTime<Utc>, u64)>,
}

impl BridgeIdentityState {
    /// Start a new connection generation and clear readiness eligibility.
    pub fn begin_connection(&mut self, generation: u64, observed_at: DateTime<Utc>) {
        self.connection_generation = generation;
        self.ready = None;
        self.ipc_observed_at = Some(observed_at);
        self.main_thread_pump = None;
    }

    /// Build a serializable last-observed snapshot.
    #[must_use]
    pub fn snapshot(&self, now: DateTime<Utc>) -> BridgeIdentitySnapshot {
        let ready = self.ready.as_ref();
        BridgeIdentitySnapshot {
            connection_generation: self.connection_generation,
            capability_state: if ready.is_some() {
                BridgeCapabilityState::Ready
            } else {
                BridgeCapabilityState::Unknown
            },
            load_generation: ready.map(|value| value.load_generation.clone()),
            protocol: ready.map(|value| value.protocol.clone()),
            runtime: ready.map(|value| value.runtime.clone()),
            supported_features: ready
                .map(|value| value.supported_features.clone())
                .unwrap_or_default(),
            loaded_code: ready.map(|value| value.loaded_code.clone()),
            source_snapshot: ready.map(|value| value.source_snapshot.clone()),
            bundle_snapshot: ready.map(|value| value.bundle_snapshot.clone()),
            ipc_liveness: self.ipc_observed_at.map(|observed_at| BridgeObservedAge {
                observed_at,
                age_ms: elapsed_ms(observed_at, now),
                provenance: "daemonFramedTraffic",
            }),
            main_thread_pump: self
                .main_thread_pump
                .map(|(observed_at, age_at_observation)| BridgeObservedAge {
                    observed_at,
                    age_ms: age_at_observation.saturating_add(elapsed_ms(observed_at, now)),
                    provenance: "bridgeCachedMainThreadPumpMonotonic",
                }),
        }
    }
}

fn elapsed_ms(then: DateTime<Utc>, now: DateTime<Utc>) -> u64 {
    u64::try_from(now.signed_duration_since(then).num_milliseconds().max(0)).unwrap_or(u64::MAX)
}

/// Why a ready/heartbeat observation or future feature requirement was rejected.
#[derive(Debug, Clone, PartialEq, Eq, Error)]
pub enum BridgeCapabilityError {
    /// PID is absent from the registry.
    #[error("unknown bridge pid {pid}")]
    UnknownPid {
        /// Requested pid.
        pid: u32,
    },
    /// PID is known but has no connected bridge.
    #[error("bridge pid {pid} is not connected")]
    NotConnected {
        /// Requested pid.
        pid: u32,
    },
    /// Observation belongs to another daemon connection generation.
    #[error("stale bridge generation for pid {pid}: expected {expected}, observed {observed}")]
    StaleGeneration {
        /// Requested pid.
        pid: u32,
        /// Current daemon connection generation.
        expected: u64,
        /// Event/dispatch connection generation.
        observed: u64,
    },
    /// Ready event was malformed or internally inconsistent.
    #[error("invalid bridge ready event: {reason}")]
    InvalidReady {
        /// Validation failure.
        reason: String,
    },
    /// Heartbeat came from a different Python package load.
    #[error("heartbeat load generation does not match ready bridge for pid {pid}")]
    LoadGenerationMismatch {
        /// Requested pid.
        pid: u32,
    },
    /// Legacy bridge sent no ready event, so support is unknown.
    #[error("bridge capabilities are unknown for pid {pid}; no ready event observed")]
    UnknownCapabilities {
        /// Requested pid.
        pid: u32,
    },
    /// Ready bridge explicitly omitted required features.
    #[error("bridge pid {pid} does not support required features: {features:?}")]
    UnsupportedFeatures {
        /// Requested pid.
        pid: u32,
        /// Missing feature names.
        features: Vec<String>,
    },
}

/// Validate bounded ready metadata before making it eligible.
pub fn validate_ready(ready: &BridgeReadyEvent) -> Result<(), BridgeCapabilityError> {
    if ready.load_generation.trim().is_empty() {
        return Err(BridgeCapabilityError::InvalidReady {
            reason: "loadGeneration is empty".to_owned(),
        });
    }
    if ready.protocol.name.trim().is_empty() || ready.protocol.version.trim().is_empty() {
        return Err(BridgeCapabilityError::InvalidReady {
            reason: "protocol identity is incomplete".to_owned(),
        });
    }
    if ready.loaded_code.algorithm.trim().is_empty() || ready.loaded_code.digest.trim().is_empty() {
        return Err(BridgeCapabilityError::InvalidReady {
            reason: "loadedCode identity is incomplete".to_owned(),
        });
    }
    if ready.source_snapshot.provenance.trim().is_empty()
        || ready.source_snapshot.algorithm.trim().is_empty()
        || ready.source_snapshot.digest.trim().is_empty()
    {
        return Err(BridgeCapabilityError::InvalidReady {
            reason: "sourceSnapshot identity/provenance is incomplete".to_owned(),
        });
    }
    if ready.bundle_snapshot.provenance.trim().is_empty()
        || ready.bundle_snapshot.algorithm.trim().is_empty()
        || ready.bundle_snapshot.digest.trim().is_empty()
    {
        return Err(BridgeCapabilityError::InvalidReady {
            reason: "bundleSnapshot identity/provenance is incomplete".to_owned(),
        });
    }
    if ready
        .supported_features
        .iter()
        .any(|feature| feature.trim().is_empty())
    {
        return Err(BridgeCapabilityError::InvalidReady {
            reason: "supportedFeatures contains an empty name".to_owned(),
        });
    }
    let mut features = ready.supported_features.clone();
    features.sort();
    if features.windows(2).any(|pair| pair[0] == pair[1]) {
        return Err(BridgeCapabilityError::InvalidReady {
            reason: "supportedFeatures contains duplicates".to_owned(),
        });
    }
    Ok(())
}
